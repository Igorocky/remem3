    @Test
    void insert_sets_autogenerated_fields() {
        //given
        DbSchema sc = new DbSchemaImpl();
        Database db = DatabaseImpl.getInMemoryDb(sc);
        db.transactionV(sc::upgrade);
        FolderEnt folder = FolderEnt.builder().name("F1").build();
        db.insert(sc.getFolderTable(), folder);
        CardTypeEnt cardType = CardTypeEnt.builder().code("C1").tableName("T2").build();
        db.insert(sc.getCardTypeTable(), cardType);
        CardEnt card = CardEnt.builder().folderId(folder.id).cardTypeId(cardType.id).build();
        assertNull(card.id);
        assertNull(card.crtTime);

        //when
        db.insert(sc.getCardTable(), card);

        //then
        assertEquals(1, card.id);
        assertCurrentTime(card.crtTime);
        CardEnt cardInDb = db.selectSingleById(CardEnt.class, sc.getCardTable(), card.id);
        assertEquals(1, cardInDb.id);
        assertEquals(card.crtTime, cardInDb.crtTime);
    }

    @Test
    void insert_doesnt_override_values_of_autogenerated_fields() {
        //given
        DbSchema sc = new DbSchemaImpl();
        Database db = DatabaseImpl.getInMemoryDb(sc);
        db.transactionV(sc::upgrade);
        FolderEnt folder = FolderEnt.builder().name("F1").build();
        db.insert(sc.getFolderTable(), folder);
        CardTypeEnt cardType = CardTypeEnt.builder().code("C1").tableName("T2").build();
        db.insert(sc.getCardTypeTable(), cardType);
        CardEnt card = CardEnt.builder().folderId(folder.id).cardTypeId(cardType.id).crtTime(-1L).build();
        assertNull(card.id);
        assertEquals(-1L, card.crtTime);

        //when
        db.insert(sc.getCardTable(), card);

        //then
        assertEquals(1, card.id);
        assertEquals(-1L, card.crtTime);
        CardEnt cardInDb = db.selectSingleById(CardEnt.class, sc.getCardTable(), card.id);
        assertEquals(1, cardInDb.id);
        assertEquals(card.crtTime, cardInDb.crtTime);
    }

    private int countRows(Database db, Table table) {
        return (int) db.selectSingle("select count(1) from " + table.getName());
    }

    private void assertCurrentTime(Long millis) {
        long curMillis = Instant.now().toEpochMilli();
        assertTrue(curMillis - 50 <= millis && millis <= curMillis + 50);
    }

