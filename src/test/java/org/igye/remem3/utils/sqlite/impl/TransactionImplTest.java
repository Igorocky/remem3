package org.igye.remem3.utils.sqlite.impl;

import org.igye.remem3.app.db.DbSchema;
import org.igye.remem3.app.db.entities.CardEnt;
import org.igye.remem3.app.db.entities.CardTypeEnt;
import org.igye.remem3.app.db.entities.FolderEnt;
import org.igye.remem3.app.db.entities.LangEnt;
import org.igye.remem3.app.db.impl.DbSchemaImpl;
import org.igye.remem3.utils.Exn;
import org.igye.remem3.utils.sqlite.Database;
import org.igye.remem3.utils.sqlite.Table;
import org.junit.jupiter.api.Test;

import java.time.Instant;
import java.util.List;

import static org.igye.remem3.app.db.impl.DbSchemaImpl.LANG_NAME;
import static org.junit.jupiter.api.Assertions.*;

class TransactionImplTest {
    @Test
    void insert_sets_autogenerated_ids() {
        //given
        Database db = DatabaseImpl.getInMemoryDb();
        DbSchema sc = new DbSchemaImpl();
        db.transactionV(sc::upgrade);
        List<LangEnt> langs = List.of(
            LangEnt.builder().name("L1").build(),
            LangEnt.builder().name("L2").build(),
            LangEnt.builder().name("L3").build()
        );

        //when
        db.transactionV(tx -> tx.insertMany(sc.getLanguageTable(), langs));

        //then
        assertEquals(1, langs.get(0).id);
        assertEquals(2, langs.get(1).id);
        assertEquals(3, langs.get(2).id);
    }

    @Test
    void select() {
        //given
        Database db = DatabaseImpl.getInMemoryDb();
        DbSchema sc = new DbSchemaImpl();
        db.transactionV(sc::upgrade);
        db.transactionV(tx -> tx.insertMany(
            sc.getLanguageTable(),
            List.of(
                LangEnt.builder().name("L1").build(),
                LangEnt.builder().name("L2").build(),
                LangEnt.builder().name("L3").build()
            )
        ));

        //when
        List<LangEnt> langs = db.transaction(tx ->
            tx.select(LangEnt.class, sc.getLanguageTable(), null, List.of(LANG_NAME), null)
        );

        //then
        assertEquals(1, langs.get(0).id);
        assertEquals(2, langs.get(1).id);
        assertEquals(3, langs.get(2).id);
    }

    @Test
    void test_history() {
        //given
        Database db = DatabaseImpl.getInMemoryDb();
        DbSchema sc = new DbSchemaImpl();
        db.transactionV(sc::upgrade);
        FolderEnt folder1 = FolderEnt.builder().name("F1").build();
        db.insert(sc.getFolderTable(), folder1);
        FolderEnt folder2 = FolderEnt.builder().name("F1").build();
        db.insert(sc.getFolderTable(), folder2);
        CardTypeEnt cardType1 = CardTypeEnt.builder().code("C1").tableName("T2").build();
        db.insert(sc.getCardTypeTable(), cardType1);
        CardTypeEnt cardType2 = CardTypeEnt.builder().code("C3").tableName("T4").build();
        db.insert(sc.getCardTypeTable(), cardType2);
        assertEquals(0, countRows(db, sc.getCardTable()));
        assertEquals(0, countRows(db, sc.getCardTable().getHistTable()));

        //when
        CardEnt card = CardEnt.builder().folderId(folder1.id).cardTypeId(cardType1.id).build();
        db.insert(sc.getCardTable(), card);

        //then
        assertEquals(1, countRows(db, sc.getCardTable()));
        assertEquals(1, countRows(db, sc.getCardTable().getHistTable()));
        CardEnt cardInDb = db.selectSingleById(CardEnt.class, sc.getCardTable(), card.id);

        assertEquals(folder1.id, cardInDb.folderId);
        assertEquals(cardType1.id, cardInDb.cardTypeId);
        throw new Exn("Not implemented");
    }

    @Test
    void insert_checks_foreign_key_constraints() {
        //given
        Database db = DatabaseImpl.getInMemoryDb();
        DbSchema sc = new DbSchemaImpl();
        db.transactionV(sc::upgrade);

        //when
        Exn actualExn = assertThrows(
            Exn.class,
            () -> db.insert(sc.getCardTable(), CardEnt.builder().folderId(17L).cardTypeId(2L).build())
        );

        //then
        assertTrue(actualExn.getCause().getMessage().contains("A foreign key constraint failed"));
    }

    @Test
    void insert_sets_autogenerated_fields() {
        //given
        Database db = DatabaseImpl.getInMemoryDb();
        DbSchema sc = new DbSchemaImpl();
        db.transactionV(sc::upgrade);
        FolderEnt folder = FolderEnt.builder().name("F1").build();
        db.insert(sc.getFolderTable(), folder);
        CardTypeEnt cardType = CardTypeEnt.builder().code("C1").tableName("T2").build();
        db.insert(sc.getCardTypeTable(), cardType);
        CardEnt card = CardEnt.builder().folderId(folder.id).cardTypeId(cardType.id).build();
        assertNull(card.id);
        assertNull(card.crtTime);

        //when
        db.insert(sc.getCardTable(), card);

        //then
        assertEquals(1, card.id);
        assertCurrentTime(card.crtTime);
        CardEnt cardInDb = db.selectSingleById(CardEnt.class, sc.getCardTable(), card.id);
        assertEquals(1, cardInDb.id);
        assertEquals(card.crtTime, cardInDb.crtTime);
    }

    @Test
    void insert_doesnt_override_values_of_autogenerated_fields() {
        //given
        Database db = DatabaseImpl.getInMemoryDb();
        DbSchema sc = new DbSchemaImpl();
        db.transactionV(sc::upgrade);
        FolderEnt folder = FolderEnt.builder().name("F1").build();
        db.insert(sc.getFolderTable(), folder);
        CardTypeEnt cardType = CardTypeEnt.builder().code("C1").tableName("T2").build();
        db.insert(sc.getCardTypeTable(), cardType);
        CardEnt card = CardEnt.builder().folderId(folder.id).cardTypeId(cardType.id).crtTime(-1L).build();
        assertNull(card.id);
        assertEquals(-1L, card.crtTime);

        //when
        db.insert(sc.getCardTable(), card);

        //then
        assertEquals(1, card.id);
        assertEquals(-1L, card.crtTime);
        CardEnt cardInDb = db.selectSingleById(CardEnt.class, sc.getCardTable(), card.id);
        assertEquals(1, cardInDb.id);
        assertEquals(card.crtTime, cardInDb.crtTime);
    }

    private int countRows(Database db, Table table) {
        return (int) db.selectSingle("select count(1) from " + table.getName());
    }

    private void assertCurrentTime(Long seconds) {
        long curSec = Instant.now().getEpochSecond();
        assertTrue(curSec - 2 <= seconds && seconds <= curSec + 2);
    }
}